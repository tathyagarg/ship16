.section text

START:
  CLS
  MOV r0, 28
  MOV r1, 28
  MOV r2, 1
  MOV r3, 0

  SETI MOVE
  VEC  2
  ENINT 0b100
  EI

  SETI _SS

LOOP:
  SETX r0
  SETY r1
  DRWSR r3
  JMP  LOOP

MOVE:
  CLS
  KSKP 1
  JMP  MOVE_UDR
  JMP  MOVE_LEFT

MOVE_UDR:
  KSKP 2
  JMP  MOVE_UD
  JMP  MOVE_RIGHT

MOVE_UD:
  KSKP 9
  JMP  MOVE_UP_OR_BLINK
  JMP  MOVE_DOWN

MOVE_RIGHT:
  SKP<GE> r0, 56
  ADD r0, r2
  RETI

MOVE_LEFT:
  SKP<LE> r0, 0
  SUB r0, r2
  RETI

MOVE_UP_OR_BLINK:
  KSKP 8
  JMP MOVE_UP
  JMP BLINK

MOVE_UP:
  SKP<LE> r1, 0
  SUB r1, r2
  RETI

MOVE_DOWN:
  SKP<GE> r1, 56
  ADD r1, r2
  RETI

BLINK:
  MOV r4, 1
  SUB r4, r3
  MOV r3, r4
  MUL r4, 3
  ADD r4, 1
  MOV r2, r4
  RETI

