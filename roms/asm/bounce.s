START:
  MOVC 0, 0
  CLS
  MOV r0, 8
  MOV r1, 0
  MOV r2, 1
  MOV r3, 1

  MOV rE, 2
  MOV rF, 1

  TCFG 1, 1
  MOV  r4, 1
  TC   r4
  TR   r4
  ENINT 2

  SETI SPEED_CHANGE
  VEC  2
  ENINT 0b100
  EI

  SETI 0

LOOP:
  CLS
  SETX r0
  SETY r1
  DRWS 38
  CALL PHYSICS
  WAIT
  JMP  LOOP

PHYSICS:
  CALL MOVE_X
  CALL MOVE_Y
  REM  r0, 64
  REM  r1, 64
  RET

MOVE_X:
  SKP<EQ> r2, 0
  JMP MOVE_X_FORWARD
  JMP MOVE_X_BACKWARD

MOVE_Y:
  SKP<EQ> r3, 0
  JMP MOVE_Y_FORWARD
  JMP MOVE_Y_BACKWARD

CMOVE_XF:
  SKP<GE> r0, 56
  RET
  MOV r2, 0
  RET

CMOVE_XB:
  SKP<LE> r0, 0
  RET
  MOV r2, 1
  RET

MOVE_X_FORWARD:
  ADD r0, rE
  JMP CMOVE_XF

MOVE_X_BACKWARD:
  SUB r0, rE
  JMP CMOVE_XB

CMOVE_YF:
  SKP<GE> r1, 56
  RET
  MOV r3, 0
  RET

CMOVE_YB:
  SKP<LE> r1, 0
  RET
  MOV r3, 1
  RET

MOVE_Y_FORWARD:
  ADD r1, rF
  JMP CMOVE_YF

MOVE_Y_BACKWARD:
  SUB r1, rF
  JMP CMOVE_YB

SPEED_CHANGE:
  KSKP 1
  JMP  INCREASE_SPEED_X
  JMP  DECREASE_SPEED_X

INCREASE_SPEED_X:
  ADD rE, 1
  RETI

DECREASE_SPEED_X:
  SKP<EQ> rE, 1
  SUB rE, 1
  RETI
