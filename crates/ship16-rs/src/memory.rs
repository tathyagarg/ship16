#[derive(Debug)]
pub struct RoomTooLarge {
    pub len: usize,
    pub max: usize,
}

impl Display for RoomTooLarge {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "ROM data is too large. Max size is {} bytes, but got {} bytes.",
            self.max, self.len
        )
    }
}
impl std::error::Error for RoomTooLarge {}

pub struct Memory(Box<[u8]>);

impl Memory {
    pub fn new() -> Self {
        let mut data = vec![0u8; ROM_SIZE + RAM_SIZE].into_boxed_slice();
        data[..FONT.len()].copy_from_slice(&FONT);

        Memory(data)
    }

    pub fn read_byte(&self, address: u16) -> u8 {
        self.0[address as usize]
    }

    pub fn read_sprite(&self, start_address: usize) -> Option<[u8; 64]> {
        let end_address = start_address + 64;
        if end_address > self.0.len() {
            return None;
        }

        Some(
            self.0[start_address..end_address]
                .try_into()
                .expect("Failed to read sprite data"),
        )
    }

    pub fn write_byte(&mut self, address: u16, value: u8) {
        if address >= RAM_BASE as u16 {
            self.0[address as usize] = value;
        }
    }

    pub fn load_rom(&mut self, data: &[u8]) -> Result<(), RoomTooLarge> {
        let base = ENTRY_POINT as usize;
        let max = ROM_SIZE - base;
        if data.len() > max {
            return Err(RoomTooLarge {
                len: data.len(),
                max,
            });
        }

        self.0[base..base + data.len()].copy_from_slice(data);
        Ok(())
    }

    pub fn read_u16(&self, address: u16) -> u16 {
        let low = self.read_byte(address) as u16;
        let high = self.read_byte(address.wrapping_add(1)) as u16;
        (high << 8) | low
    }

    pub fn draw_color(&mut self, color: u8, x: u8, y: u8) {
        let index = y as usize * 64 + x as usize;
        self.0[RAM_BASE + index] = color;
    }

    pub fn vram(&self) -> &[u8] {
        &self.0[RAM_BASE..RAM_BASE + VRAM_SIZE]
    }

    pub fn vram_mut(&mut self) -> &mut [u8] {
        &mut self.0[RAM_BASE..RAM_BASE + VRAM_SIZE]
    }
}

impl Default for Memory {
    fn default() -> Self {
        Self::new()
    }
}
